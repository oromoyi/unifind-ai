"""Regenerate database/schema.sql and database/seed_reference.sql from the SQLAlchemy models.
Run from the repository root:  python database/generate_sql.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "backend"))
os.environ.setdefault("SECRET_KEY", "x" * 40)

from sqlalchemy.dialects import mysql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import create_app  # noqa: E402
from app.config import TestConfig  # noqa: E402
from app.extensions import db  # noqa: E402
import seed_lib  # noqa: E402

app = create_app(TestConfig)
with app.app_context():
    out = ["-- UniFind AI - MySQL 8 / MariaDB 10.5+ schema (generated by database/generate_sql.py)",
           "CREATE DATABASE IF NOT EXISTS unifind CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
           "USE unifind;", "SET FOREIGN_KEY_CHECKS = 0;", ""]
    for t in db.metadata.sorted_tables:
        out.append(f"DROP TABLE IF EXISTS `{t.name}`;")
    out.append("")
    for t in db.metadata.sorted_tables:
        ddl = str(CreateTable(t).compile(dialect=mysql.dialect())).strip().rstrip(";")
        ddl += " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;"
        out.append(ddl + "\n")
        for ix in sorted(t.indexes, key=lambda i: i.name):
            out.append(str(CreateIndex(ix).compile(dialect=mysql.dialect())).strip() + ";")
        out.append("")
    out.append("SET FOREIGN_KEY_CHECKS = 1;")
    open(os.path.join(HERE, "schema.sql"), "w", encoding="utf-8").write("\n".join(out) + "\n")

q = lambda s: "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"
seed = ["-- Reference data: permissions, roles, categories, campus locations (no personal data)", "USE unifind;", ""]
for code, d in seed_lib.PERMISSIONS.items():
    seed.append(f"INSERT IGNORE INTO permissions (code, description) VALUES ({q(code)}, {q(d)});")
for name, (d, _) in seed_lib.ROLES.items():
    seed.append(f"INSERT IGNORE INTO roles (name, description) VALUES ({q(name)}, {q(d)});")
for name, (_, codes) in seed_lib.ROLES.items():
    for c in codes:
        seed.append(f"INSERT IGNORE INTO role_permissions (role_id, permission_id) SELECT r.id, p.id FROM roles r, permissions p WHERE r.name={q(name)} AND p.code={q(c)};")
for n in seed_lib.CATEGORIES:
    seed.append(f"INSERT IGNORE INTO item_categories (name, is_active) VALUES ({q(n)}, 1);")
for n, z, x, y in seed_lib.LOCATIONS:
    seed.append(f"INSERT IGNORE INTO campus_locations (name, zone, x, y, is_active) VALUES ({q(n)}, {q(z)}, {x}, {y}, 1);")
seed.append("")
seed.append("-- Demo users, lost/found items, claims and handovers are created by `python backend/seed.py`")
seed.append("-- (it calls the real API so password hashes, audit logs, matches and notifications are genuine).")
open(os.path.join(HERE, "seed_reference.sql"), "w", encoding="utf-8").write("\n".join(seed) + "\n")
print("generated")
